# 官方版本清单
VERSION_MANIFEST = "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json"
# Fabric 服务端下载
FABRIC_META = "https://meta.fabricmc.net/v2/versions/loader"


def get_game_dir():
    """获取游戏根目录"""
    if CONFIG:
        return Path(CONFIG.get("game_dir", str(Path.home() / ".minecraft")))
    return Path.home() / ".minecraft"


def get_servers_dir():
    """获取服务器目录"""
    d = get_game_dir() / "voxel_servers"
    d.mkdir(parents=True, exist_ok=True)
    return d


def list_servers():
    """列出所有服务器"""
    d = get_servers_dir()
    servers = []
    if d.exists():
        for child in d.iterdir():
            if child.is_dir() and (child / "server.properties").exists():
                servers.append(child.name)
    return sorted(servers)


def get_server_info(name):
    """获取服务器信息"""
    d = get_servers_dir() / name
    props_file = d / "server.properties"
    info = {"name": name, "path": str(d), "port": "25565", "motd": "VoxelLauncher Server"}
    if props_file.exists():
        try:
            for line in props_file.read_text(encoding="utf-8").splitlines():
                if "=" in line:
                    k, v = line.split("=", 1)
                    if k.strip() == "server-port":
                        info["port"] = v.strip()
                    elif k.strip() == "motd":
                        info["motd"] = v.strip()
                    elif k.strip() == "max-players":
                        info["max_players"] = v.strip()
        except Exception:
            pass
    return info


def download_vanilla_server(version, progress_cb=None):
    """下载原版服务端"""
    # 获取版本信息
    resp = requests.get(VERSION_MANIFEST, timeout=30)
    manifest = resp.json()
    version_url = None
    for v in manifest.get("versions", []):
        if v.get("id") == version:
            version_url = v.get("url")
            break
    if not version_url:
        raise ValueError("找不到版本: " + version)

    resp = requests.get(version_url, timeout=30)
    version_info = resp.json()
    server_url = version_info.get("downloads", {}).get("server", {}).get("url")
    if not server_url:
        raise ValueError("该版本没有服务端")

    # 下载
    servers_dir = get_servers_dir()
    server_dir = servers_dir / ("vanilla-" + version)
    server_dir.mkdir(parents=True, exist_ok=True)
