def download_fabric_server(version, progress_cb=None, java_path="java"):
    """下载并安装 Fabric 服务端"""
    if progress_cb:
        progress_cb("获取 Fabric 版本信息...")

    # 获取最新的 fabric loader 版本
    resp = requests.get(FABRIC_META + "/" + version, timeout=30)
    loaders = resp.json()
    if not loaders:
        raise ValueError("找不到 Fabric 版本")
    loader_version = loaders[0].get("loader", {}).get("version")

    # 获取最新的 installer 版本
    installer_resp = requests.get("https://meta.fabricmc.net/v2/versions/installer", timeout=30)
    installers = installer_resp.json()
    installer_version = installers[0].get("version") if installers else "1.0.1"

    servers_dir = get_servers_dir()
    server_dir = servers_dir / ("fabric-" + version)
    server_dir.mkdir(parents=True, exist_ok=True)

    # 下载 Fabric 安装器
    installer_url = "https://maven.fabricmc.net/net/fabricmc/fabric-installer/{}/fabric-installer-{}.jar".format(
        installer_version, installer_version)
    installer_path = server_dir / "fabric-installer.jar"

    if progress_cb:
        progress_cb("下载 Fabric 安装器...")

    resp = requests.get(installer_url, stream=True, timeout=120)
    total = int(resp.headers.get("content-length", 0))
    downloaded = 0
    with open(installer_path, "wb") as f:
        for chunk in resp.iter_content(chunk_size=8192):
            f.write(chunk)
            downloaded += len(chunk)
            if progress_cb and total > 0:
                pct = downloaded * 100 // total
