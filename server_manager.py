class MinecraftServer:
    """Minecraft 服务器实例"""

    def __init__(self, name, java_path=None, memory="2G"):
        self.name = name
        self.server_dir = get_servers_dir() / name
        self.java_path = java_path or "java"
        self.memory = memory
        self.process = None
        self.output_callback = None
        self._running = False

    def start(self):
        """启动服务器"""
        if self._running:
            return False
        # 自动检测启动 jar: Fabric 用 fabric-server-launch.jar，原版用 server.jar
        jar_path = self.server_dir / "fabric-server-launch.jar"
        if not jar_path.exists():
            jar_path = self.server_dir / "server.jar"
        if not jar_path.exists():
            # 找任何可启动的 jar
            for f in self.server_dir.glob("*.jar"):
                if "launch" in f.name.lower() or "server" in f.name.lower():
                    jar_path = f
                    break
        if not jar_path.exists():
            raise FileNotFoundError("找不到服务器启动 jar")

        cmd = [
            self.java_path,
            "-Xmx" + self.memory,
            "-Xms" + self.memory,
            "-jar", str(jar_path),
            "nogui"
        ]

        self.process = subprocess.Popen(
            cmd,
            cwd=str(self.server_dir),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1
        )
        self._running = True

        # 启动输出读取线程
        t = threading.Thread(target=self._read_output, daemon=True)
        t.start()

        return True

    def _read_output(self):
        """读取服务器输出"""
        try:
            for line in self.process.stdout:
                line = line.strip()
                if line and self.output_callback:
                    self.output_callback(line)
        except Exception:
            pass
        finally:
            self._running = False
            if self.output_callback:
                self.output_callback("[服务器已停止]")

    def stop(self):
        """停止服务器"""
        if self.process and self._running:
            try:
                self.process.stdin.write("stop\n")
                self.process.stdin.flush()
                # 等待10秒
                try:
                    self.process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    self.process.kill()
            except Exception:
                try:
                    self.process.kill()
                except Exception:
                    pass
        self._running = False

    def send_command(self, cmd):
        """发送命令到服务器"""
        if self.process and self._running:
            try:
                self.process.stdin.write(cmd + "\n")
                self.process.stdin.flush()
                return True
            except Exception:
                return False
        return False

    def is_running(self):
        return self._running

    def get_local_ip(self):
        """获取本机局域网IP"""
        import socket
        try:
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            s.connect(("8.8.8.8", 80))
            ip = s.getsockname()[0]
            s.close()
            return ip
        except Exception:
            return "127.0.0.1"

    def get_port(self):
        """获取服务器端口"""
        props_file = self.server_dir / "server.properties"
        if props_file.exists():
            try:
                for line in props_file.read_text(encoding="utf-8").splitlines():
                    if line.startswith("server-port="):
                        return line.split("=", 1)[1].strip()
            except Exception:
                pass
        return "25565"


def delete_server(name):
    """删除服务器"""
    import shutil
    d = get_servers_dir() / name
    if d.exists():
        shutil.rmtree(d)
        return True
    return False
